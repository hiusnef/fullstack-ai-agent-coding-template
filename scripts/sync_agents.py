#!/usr/bin/env python3
"""Generate per-agent config from the single source of truth in `.ai/`.

Usage:
    python scripts/sync_agents.py          # write generated files
    python scripts/sync_agents.py --check  # exit 1 if generated files are stale (for CI)
    python scripts/sync_agents.py --stage  # write, then git add / git rm the generated files (pre-commit)

Source layout (edit only these):
    .ai/rules/*.md          frontmatter: description, alwaysApply: true | globs: [..]
    .ai/skills/<n>/SKILL.md Agent Skills format (name, description)
    .ai/agents/<agent>.md   optional agent-specific extras (claude, copilot, codex, antigravity, cursor)
    .ai/mcp.json            {"servers": {name: {command, args, env}}}
    .ai/permissions.json    {"allow": [..], "deny": [..]} in Claude Code permission syntax
    .ai/config.json         {"targets": [..]} agents to generate for (see TARGETS)

Outputs (only for the agents listed in .ai/config.json; AGENTS.md is always written):
    AGENTS.md                                 Codex, Copilot, Cursor, Antigravity (and others) read natively
    CLAUDE.md                                 Claude Code (imports AGENTS.md)
    .claude/rules/, .claude/skills/, .claude/settings.json, .mcp.json
    .github/copilot-instructions.md, .github/instructions/*.instructions.md, .vscode/mcp.json
    .agents/rules/, .agents/skills/           Antigravity (+ Codex skills)
    .codex/config.toml                        Codex MCP servers
    .cursor/rules/*.mdc, .cursor/mcp.json
    .gitattributes                            marks generated files so PR diffs collapse them
    .vscode/settings.json                     hides generated copies from the VS Code explorer/search (copilot)
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / ".ai"
MANIFEST = SRC / ".generated.json"
HEADER = "<!-- GENERATED by scripts/sync_agents.py from .ai/ - do not edit by hand -->"
ENV_RE = re.compile(r"\$\{env:([A-Z0-9_]+)\}")
# path prefixes each agent owns; AGENTS.md is shared by all of them
TARGETS = {
    "claude": ("CLAUDE.md", ".claude/", ".mcp.json"),
    "copilot": (".github/copilot-instructions.md", ".github/instructions/", ".vscode/"),
    "codex": (".codex/", ".agents/skills/"),
    "antigravity": (".agents/",),
    "cursor": (".cursor/",),
}
# folders that are pure copies of .ai/ - hidden in the editor to avoid duplicate search hits
COPIES = (".claude/rules", ".claude/skills", ".github/instructions", ".agents", ".cursor/rules")


# ---------------------------------------------------------------- parsing
@dataclass
class Rule:
    name: str
    description: str
    always: bool
    globs: list[str]
    body: str
    src: str


def parse_frontmatter(text: str) -> tuple[dict, str]:
    if not text.startswith("---"):
        return {}, text
    _, fm, body = text.split("---", 2)
    meta: dict = {}
    for line in fm.strip().splitlines():
        if ":" not in line:
            continue
        key, val = line.split(":", 1)
        val = val.strip()
        if val.startswith("["):
            meta[key.strip()] = json.loads(val)
        elif val in ("true", "false"):
            meta[key.strip()] = val == "true"
        else:
            meta[key.strip()] = val.strip("\"'")
    return meta, body.strip() + "\n"


def load_rules() -> list[Rule]:
    rules = []
    for p in sorted((SRC / "rules").glob("*.md")):
        meta, body = parse_frontmatter(p.read_text(encoding="utf-8"))
        globs = meta.get("globs", [])
        always = bool(meta.get("alwaysApply", not globs))
        if always and globs:
            sys.exit(f"{p}: use either alwaysApply or globs, not both")
        rules.append(Rule(re.sub(r"^\d+-", "", p.stem), meta.get("description", ""),
                          always, globs, body, p.relative_to(ROOT).as_posix()))
    return rules


def load_skills() -> list[tuple[str, str, Path]]:
    out = []
    for d in sorted((SRC / "skills").glob("*/SKILL.md")):
        meta, _ = parse_frontmatter(d.read_text(encoding="utf-8"))
        out.append((meta.get("name", d.parent.name), meta.get("description", ""), d.parent))
    return out


def project_name(rules: list[Rule]) -> str:
    for r in rules:
        m = re.search(r"^# Project: (.+)$", r.body, re.M)
        if m:
            return m.group(1).strip()
    return ROOT.name


def extra(agent: str) -> str:
    p = SRC / "agents" / f"{agent}.md"
    return "\n" + p.read_text(encoding="utf-8").strip() + "\n" if p.exists() else ""


# ---------------------------------------------------------------- rendering
def render(rules, skills, mcp, perms, targets) -> dict[str, str]:
    files: dict[str, str] = {}
    always = [r for r in rules if r.always]
    scoped = [r for r in rules if not r.always]

    # AGENTS.md: the shared, always-on instructions
    parts = [HEADER, ""] + [r.body for r in always]
    if scoped:
        parts.append("# Scoped rules\nBefore editing files matching these patterns, read the linked rule file:\n")
        parts += [f"- `{', '.join(r.globs)}` -> `{r.src}` ({r.description})" for r in scoped]
        parts.append("")
    if skills:
        parts.append("# Skills (step-by-step playbooks)\nWhen a task matches, follow the playbook:\n")
        parts += [f"- **{n}** (`.ai/skills/{d.name}/SKILL.md`): {desc}" for n, desc, d in skills]
        parts.append("")
    if "codex" in targets:
        parts.append(extra("codex"))
    files["AGENTS.md"] = "\n".join(parts).rstrip() + "\n"

    # Claude Code: CLAUDE.md imports AGENTS.md
    files["CLAUDE.md"] = f"{HEADER}\n# {project_name(rules)}\n\n@AGENTS.md\n{extra('claude')}"

    # GitHub Copilot: reads AGENTS.md in agent mode; this file covers chat / code review
    files[".github/copilot-instructions.md"] = (
        f"{HEADER}\nFollow the project instructions in `AGENTS.md` at the repository root.\n"
        "Key guardrails (duplicated here because some Copilot surfaces do not load AGENTS.md):\n\n"
        + next((r.body for r in always if r.name == "security"), "") + extra("copilot"))

    for r in scoped:
        files[f".claude/rules/{r.name}.md"] = (
            f"---\npaths:\n" + "".join(f"  - \"{g}\"\n" for g in r.globs) + f"---\n{HEADER}\n{r.body}")
        files[f".github/instructions/{r.name}.instructions.md"] = (
            f"---\napplyTo: \"{','.join(r.globs)}\"\n---\n{HEADER}\n{r.body}")
        files[f".cursor/rules/{r.name}.mdc"] = (
            f"---\ndescription: {r.description}\nglobs: {','.join(r.globs)}\nalwaysApply: false\n---\n{r.body}")
        files[f".agents/rules/{r.name}.md"] = (
            f"---\ntrigger: glob\nglobs: {','.join(r.globs)}\ndescription: {r.description}\n---\n{HEADER}\n{r.body}")

    # Skills: copy every file of every skill folder
    for _, _, d in skills:
        for f in d.rglob("*"):
            if f.is_file():
                rel = f.relative_to(SRC / "skills").as_posix()
                content = f.read_text(encoding="utf-8")
                for target in (".claude/skills", ".agents/skills"):
                    files[f"{target}/{rel}"] = content

    # MCP servers
    servers = mcp.get("servers", {})
    claude_srv, cursor_srv, vscode_srv, codex = {}, {}, {}, [f"# {HEADER[5:-4]}\n"]
    for name, s in servers.items():
        env = s.get("env", {})
        base = {"command": s["command"], "args": s.get("args", [])}
        claude_srv[name] = {**base, "env": {k: ENV_RE.sub(r"${\1}", v) for k, v in env.items()}}
        cursor_srv[name] = {**base, "env": env}
        vscode_srv[name] = {"type": "stdio", **base, "env": env}
        codex.append(f"[mcp_servers.{name}]\ncommand = {json.dumps(s['command'])}\n"
                     f"args = {json.dumps(base['args'])}\n")
        passthrough = [m for v in env.values() for m in ENV_RE.findall(v)]
        static = {k: v for k, v in env.items() if not ENV_RE.search(v)}
        if passthrough:
            codex.append(f"env_vars = {json.dumps(passthrough)}\n")
        if static:
            codex.append(f"env = {{ {', '.join(f'{k} = {json.dumps(v)}' for k, v in static.items())} }}\n")
        codex.append("\n")
    dump = lambda o: json.dumps(o, indent=2) + "\n"
    files[".mcp.json"] = dump({"mcpServers": claude_srv})
    files[".cursor/mcp.json"] = dump({"mcpServers": cursor_srv})
    files[".vscode/mcp.json"] = dump({"servers": vscode_srv})
    files[".codex/config.toml"] = "".join(codex)

    # Claude Code permissions mirroring the security rule
    files[".claude/settings.json"] = dump({"permissions": {
        "allow": perms.get("allow", []), "deny": perms.get("deny", [])}})

    # Keep only the selected agents, then add the "hide generated files" helpers
    owned = tuple(prefix for t in targets for prefix in TARGETS[t])
    files = {p: c for p, c in files.items() if p == "AGENTS.md" or p.startswith(owned)}
    hidden = {d: True for d in COPIES if any(p.startswith(d + "/") for p in files)}
    if "copilot" in targets:
        files[".vscode/settings.json"] = dump({"files.exclude": hidden, "search.exclude": hidden})
    files[".gitattributes"] = f"# {HEADER[5:-4]}\n" + "".join(
        f"{p} linguist-generated=true\n" for p in sorted(files))
    return files


def load_targets() -> list[str]:
    targets = json.loads((SRC / "config.json").read_text(encoding="utf-8")).get("targets", [])
    unknown = sorted(set(targets) - set(TARGETS))
    if unknown:
        sys.exit(f".ai/config.json: unknown targets {unknown}; choose from {sorted(TARGETS)}")
    return targets


def remove(path: Path) -> None:
    """Delete a stale file and any directories it leaves empty."""
    path.unlink(missing_ok=True)
    for d in path.parents:
        if d == ROOT or any(d.iterdir()):
            break
        d.rmdir()


# ---------------------------------------------------------------- main
def main() -> int:
    check = "--check" in sys.argv
    load_json = lambda name: json.loads((SRC / name).read_text(encoding="utf-8"))
    files = render(load_rules(), load_skills(), load_json("mcp.json"), load_json("permissions.json"),
                   load_targets())
    old = set(json.loads(MANIFEST.read_text())) if MANIFEST.exists() else set()
    stale = sorted(old - set(files))

    drift = [p for p, c in files.items()
             if not (ROOT / p).exists() or (ROOT / p).read_text(encoding="utf-8") != c]
    drift += [p for p in stale if (ROOT / p).exists()]
    if check:
        if drift:
            print("Agent config out of date. Run: python scripts/sync_agents.py\n  " + "\n  ".join(drift))
            return 1
        print("Agent config up to date.")
        return 0

    for p in stale:
        remove(ROOT / p)
    for p, c in files.items():
        dest = ROOT / p
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(c, encoding="utf-8")
    MANIFEST.write_text(json.dumps(sorted(files), indent=2) + "\n")
    if "--stage" in sys.argv:
        subprocess.run(["git", "add", "--", MANIFEST.relative_to(ROOT).as_posix(), *files], cwd=ROOT, check=True)
        if stale:
            subprocess.run(["git", "rm", "-q", "--cached", "--ignore-unmatch", "--", *stale], cwd=ROOT, check=True)
    print(f"Generated {len(files)} files ({len(drift)} changed, {len(stale)} removed).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
